# Sort by length descending to avoid partial match issues (longer names first)
$sortedKeys = $renames.Keys | Sort-Object { $_.Length } -Descending

$files = Get-ChildItem -Recurse -Include "*.c","*.h" | Where-Object { $_.FullName -notmatch '\\Debug\\' }
$changedFiles = 0

foreach ($file in $files) {
    $content = Get-Content -Raw $file.FullName
    $newContent = $content
    foreach ($old in $sortedKeys) {
        $new = $renames[$old]
        if ($newContent -match [regex]::Escape($old)) {
            $newContent = $newContent -replace "\b$([regex]::Escape($old))\b", $new
        }
    }
    if ($newContent -ne $content) {
        Set-Content -NoNewline $file.FullName $newContent
        $changedFiles++
        Write-Host "  Updated: $($file.FullName -replace [regex]::Escape((Get-Location).Path + '\'), '')"
    }
}

